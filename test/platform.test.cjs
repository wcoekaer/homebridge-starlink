const { test } = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const grpc = require('@grpc/grpc-js');
const loader = require('@grpc/proto-loader');
const { StarlinkPlatform } = require('../dist/platform');
const { demoTelemetry } = require('../dist/demo');
test('Homebridge lifecycle registers camera and sensors, restores cache, and reports a genuine outage', { timeout: 10000 }, async t => {
  const { HomebridgeAPI } = await import('../node_modules/homebridge/dist/api.js');
  const api = new HomebridgeAPI();
  const d = demoTelemetry(); let offline = false;
  const schema = loader.loadSync(path.join(__dirname, '../proto/starlink.proto'), { keepCase: true });
  const root = grpc.loadPackageDefinition(schema), server = new grpc.Server();
  server.addService(root.SpaceX.API.Device.Device.service, { Handle(call, done) {
    done(null, call.request.get_status ? { dish_get_status: { ...d.status, ...(offline ? { outage: { cause: 5 } } : {}) } } : { dish_get_history: d.history });
  } });
  const port = await new Promise((resolve, reject) => server.bindAsync('127.0.0.1:0', grpc.ServerCredentials.createInsecure(), (err, port) => err ? reject(err) : resolve(port)));
  t.after(() => server.forceShutdown());
  const created = [], removed = [], registeredPlugins = [];
  api.registerPlatformAccessories = (plugin, _platform, items) => { registeredPlugins.push(plugin); created.push(...items); };
  api.unregisterPlatformAccessories = (_plugin, _platform, items) => removed.push(...items);
  api.updatePlatformAccessories = () => {};
  const logger = { info() {}, warn() {}, debug() {}, error() {} };
  const config = { platform: 'Starlink', host: '127.0.0.1', port, outageDelaySeconds: 0, recoveryDelaySeconds: 0 };
  const p = new StarlinkPlatform(logger, config, api);
  t.after(() => api.emit('shutdown'));
  api.emit('didFinishLaunching');
  await new Promise(resolve => p.monitor.once('update', resolve));
  assert.equal(created.length, 4);
  assert.deepEqual(registeredPlugins, ['@wcoekaer/homebridge-starlink']);
  assert.deepEqual(created.map(a => a.UUID).sort(), ['outage', 'degraded', 'unreachable', 'camera'].map(kind => api.hap.uuid.generate(`homebridge-starlink:127.0.0.1:${port}:${kind}`)).sort(), 'scoped package preserves all legacy HomeKit accessory identities');
  assert.equal(p.sensors.get('outage').getCharacteristic(api.hap.Characteristic.ContactSensorState).value, 0);
  const camera = created.find(a => a.displayName.includes('Dashboard'));
  assert.ok(camera.getService(api.hap.Service.CameraRTPStreamManagement));
  offline = true; await p.monitor.poll();
  assert.equal(p.sensors.get('outage').getCharacteristic(api.hap.Characteristic.ContactSensorState).value, 1);
  api.emit('shutdown');
  const next = new HomebridgeAPI(), duplicates = [];
  next.registerPlatformAccessories = (_p, _n, items) => duplicates.push(...items);
  next.unregisterPlatformAccessories = (_p, _n, items) => removed.push(...items);
  next.updatePlatformAccessories = () => {};
  const restored = new StarlinkPlatform(logger, { ...config, camera: { enabled: false } }, next);
  for (const a of created) restored.configureAccessory(a);
  t.after(() => next.emit('shutdown'));
  next.emit('didFinishLaunching');
  await new Promise(resolve => restored.monitor.once('update', resolve));
  assert.equal(duplicates.length, 0); assert.equal(removed.length, 1); assert.equal(removed[0].UUID, camera.UUID);
});
